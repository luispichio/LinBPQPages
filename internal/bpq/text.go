func bytesTrimRight(value []byte, cutset string) []byte {
	return bytes.TrimRight(value, cutset)
}

func decodeWindows1252(value []byte) string {
	var builder strings.Builder
	builder.Grow(len(value))
	for _, character := range value {
		if character >= 0x80 && character <= 0x9f {
			builder.WriteRune(windows1252High[character-0x80])
		} else {
			builder.WriteRune(rune(character))
		}
	}
	return builder.String()
}

// decodeHighTable reemplaza los bytes >= 0x80 con la tabla de 128 runas
// recibida; los bytes ASCII se copian sin cambios.
func decodeHighTable(value []byte, table []rune) string {
	var builder strings.Builder
	builder.Grow(len(value))
	for _, character := range value {
		if character < 0x80 {
			builder.WriteByte(character)
			continue
		}
		builder.WriteRune(table[character-0x80])
	}
	return builder.String()
}

func decodeCP437(value []byte) string {
	return decodeHighTable(value, cp437High)
}

func decodeCP1251(value []byte) string {
	return decodeHighTable(value, cp1251High)
}

// guessLegacyCharset decide entre CP437, CP1251 y Windows-1252 cuando no hay
// charset declarado. Es el puerto directo de TrytoGuessCode de utf8Routines.c:
// si más del 90 % de los bytes altos pertenecen al renglón de dibujo de cajas
// de CP437 (0xB0–0xDF) se asume CP437; si los bytes altos superan a las letras
// ASCII se asume CP1251; en cualquier otro caso, Windows-1252.
func guessLegacyCharset(value []byte) int {
	above127, lineDraw, numericAndSpaces := 0, 0, 0
	for _, character := range value {
		if character < 65 {
			numericAndSpaces++
			continue
		}
		if character > 127 {
			above127++
			if character > 175 && character < 224 {
				lineDraw++
			}
		}
	}
	if above127 == 0 {
		return 1252
	}
	if lineDraw > (above127*9)/10 {
		return 437
	}
	if len(value)-(numericAndSpaces+above127) < above127 {
		return 1251
	}
	return 1252
}

// decodeAuto elige la codificación del texto sin charset declarado con la
// misma política que el webmail de LinBPQ (WebIsUTF8 + TrytoGuessCode): si los
// bytes son UTF-8 válidos se conservan; si no, se conjetura un codepage
// heredado. El indicador UTF8 de DIRMES.SYS no participa de la decisión.
func decodeAuto(value []byte) string {
	if utf8.Valid(value) {
		return string(value)
	}
	switch guessLegacyCharset(value) {
	case 437:
		return decodeCP437(value)
	case 1251:
		return decodeCP1251(value)
	default:
		return decodeWindows1252(value)
	}
}

func validUTF8(value []byte) string {
	if utf8.Valid(value) {
		return string(value)
	}
	return strings.ToValidUTF8(string(value), "�")
}
